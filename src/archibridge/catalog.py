"""Searchable list of Archicad commands, with their Tapir schemas.

data/catalog.json is generated by scripts/update_catalog.py.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from importlib import resources
from typing import Any, Iterator

from . import policy

SUMMARY_LENGTH = 160
SCHEMA_DEPTH = 3
BUILTIN_DOCS = "https://archicadapi.graphisoft.com/archicadPythonPackage/archicad.releases.ac29.html"


@lru_cache(maxsize=1)
def _data() -> dict:
    text = resources.files("archibridge").joinpath("data/catalog.json").read_text("utf-8")
    return json.loads(text)


def _tapir_commands() -> Iterator[tuple[str, dict]]:
    for group in _data()["groups"]:
        for command in group["commands"]:
            yield group["name"], command


@lru_cache(maxsize=1)
def _by_name() -> dict[str, dict]:
    return {command["name"]: command for _, command in _tapir_commands()}


def tapir_version() -> str:
    return _data()["tapirVersion"]


def resolve(command: str) -> str:
    """Accepts a short built-in name such as "GetAllElements" or "IsAlive"."""
    if command.startswith("API.") or command in _by_name():
        return command
    if command in _data()["builtin"]:
        return "API." + command
    return command


def _minimum_archicad(description: str) -> int | None:
    match = re.search(r"Available from Archicad (\d+)", description)
    return int(match.group(1)) if match else None


def _entry(name: str, group: str, description: str) -> dict:
    entry: dict[str, Any] = {
        "name": name,
        "group": group,
        "access": policy.classify(name),
        "summary": description[:SUMMARY_LENGTH],
    }
    minimum = _minimum_archicad(description)
    if minimum:
        entry["minimumArchicad"] = minimum
    return entry


def _all_entries() -> Iterator[dict]:
    for group, command in _tapir_commands():
        yield _entry(command["name"], group, command["description"])
    for name in _data()["builtin"]:
        yield _entry("API." + name, "Built-in", "Built into Archicad. Works without Tapir.")


def search(query: str = "", access: str = "any", limit: int = 40) -> dict:
    """Finds commands whose name, group or description holds every word of the query."""
    words = query.lower().split()
    descriptions = {name: command["description"] for name, command in _by_name().items()}
    matches = []
    for entry in _all_entries():
        if access != "any" and entry["access"] != access:
            continue
        text = " ".join(
            (entry["name"], entry["group"], descriptions.get(entry["name"], ""))
        ).lower()
        if all(word in text for word in words):
            matches.append(entry)
    groups = [group["name"] for group in _data()["groups"]]
    return {
        "total": len(matches),
        "commands": matches[:limit],
        "groups": groups if not words else None,
    }


def _references(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                yield value.removeprefix("#/")
            else:
                yield from _references(value)
    elif isinstance(node, list):
        for item in node:
            yield from _references(item)


def _definitions(roots: list, depth: int) -> tuple[dict, list[str]]:
    known = _data()["definitions"]
    found: dict[str, Any] = {}
    frontier = {name for root in roots for name in _references(root)}
    for _ in range(depth):
        fresh = sorted(name for name in frontier if name in known and name not in found)
        if not fresh:
            return found, []
        found.update((name, known[name]) for name in fresh)
        frontier = {reference for name in fresh for reference in _references(known[name])}
    return found, sorted(name for name in frontier if name in known and name not in found)


def schema(name: str, depth: int = SCHEMA_DEPTH) -> dict:
    """Returns a command's schemas, or one shared definition by its own name."""
    name = name.removeprefix("#/")
    if name.startswith("API.") or (name in _data()["builtin"] and name not in _by_name()):
        return {
            "name": resolve(name),
            "access": policy.classify(name),
            "documentation": BUILTIN_DOCS,
            "note": "Built-in commands have no schema here. See the documentation.",
        }
    command = _by_name().get(name)
    if command is None:
        definition = _data()["definitions"].get(name)
        if definition is None:
            raise KeyError(f"Unknown command or definition: {name}")
        definitions, more = _definitions([definition], depth)
        return {"name": name, "definition": definition, "definitions": definitions, "moreDefinitions": more}

    roots = [command["inputScheme"], command["outputScheme"]]
    definitions, more = _definitions(roots, depth)
    return {
        "name": name,
        "access": policy.classify(name),
        "tapirVersion": command["version"],
        "description": command["description"],
        "input": command["inputScheme"],
        "output": command["outputScheme"],
        "definitions": definitions,
        "moreDefinitions": more,
    }
